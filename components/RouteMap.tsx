// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function computeBounds(coords: [number, number][]): {
  ne: [number, number];
  sw: [number, number];
} {
  let minLng = Infinity, maxLng = -Infinity, minLat = Infinity, maxLat = -Infinity;
  for (const [lng, lat] of coords) {
    if (lng < minLng) minLng = lng;
    if (lng > maxLng) maxLng = lng;
    if (lat < minLat) minLat = lat;
    if (lat > maxLat) maxLat = lat;
  }
  return { ne: [maxLng, maxLat], sw: [minLng, minLat] };
}

function hotspotColor(
  hs: Hotspot, unlockedIds: Set<string>, visitedIds: Set<string>,
): string {
  if (unlockedIds.has(hs.id)) return RouteColors.hotspotActive;
  if (visitedIds.has(hs.id)) return RouteColors.hotspotVisited;
  if (hs.isActive) return RouteColors.hotspotLocked;
  return RouteColors.hotspotWaypoint;
}

function haversineM(
  [lng1, lat1]: [number, number], [lng2, lat2]: [number, number],
): number {
  const R = 6371000;
  const toRad = Math.PI / 180;
  const dLat = (lat2 - lat1) * toRad;
  const dLng = (lng2 - lng1) * toRad;
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(lat1 * toRad) * Math.cos(lat2 * toRad) * Math.sin(dLng / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

function sampleDirectionDots(
  coords: [number, number][], intervalM: number,
): GeoJSON.Feature[] {
  if (coords.length < 2) return [];
  const dots: GeoJSON.Feature[] = [];
  let accumulated = 0;
  for (let i = 1; i < coords.length; i++) {
    accumulated += haversineM(coords[i - 1], coords[i]);
    if (accumulated >= intervalM) {
      accumulated = 0;
      dots.push({
        type: 'Feature',
        properties: {},
        geometry: { type: 'Point', coordinates: coords[i] },
      });
    }
  }
  return dots;
}

// ---------------------------------------------------------------------------
// Marker sub-components — ALL use native RN views (no glyphs, works offline)
