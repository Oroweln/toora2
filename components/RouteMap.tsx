let MapLibreGL: typeof import('@maplibre/maplibre-react-native');
if (Platform.OS !== 'web') {
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  MapLibreGL = require('@maplibre/maplibre-react-native');
}

// Pre-extracted map labels — only important ones rendered as native views
// Generated by: node scripts/extract-labels.js
let mapLabelsGeoJSON: GeoJSON.FeatureCollection | null = null;
try {
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  mapLabelsGeoJSON = require('../src/data/map-labels.json');
} catch {
  console.warn('RouteMap: map-labels.json not found — labels will not render');
}

// Filter labels to only the most important ones for MarkerView rendering
// (MarkerView = real RN views, so we limit count for performance)
interface MapLabel {
  name: string;
  type: string;
  class?: string;
  rank?: number;
  coordinate: [number, number];
  fontSize: number;
  color: string;
  bold: boolean;
}

function buildAllLabels(): MapLabel[] {
  if (!mapLabelsGeoJSON) return [];
  const labels: MapLabel[] = [];

  for (const f of mapLabelsGeoJSON.features) {
    const p = f.properties;
    if (!p || !p.name) continue;
    const coords = (f.geometry as GeoJSON.Point).coordinates as [number, number];

    let fontSize = 10;
    let color = '#444444';
    let bold = false;

    if (p.type === 'place') {
      if (p.class === 'city') { fontSize = 16; color = '#1a1a1a'; bold = true; }
      else if (p.class === 'town') { fontSize = 13; color = '#333333'; bold = true; }
      else if (p.class === 'village') { fontSize = 11; color = '#444444'; }
      else if (p.class === 'suburb' || p.class === 'quarter') { fontSize = 10; color = '#555555'; }
      else { fontSize = 9; color = '#666666'; } // hamlet, neighbourhood, isolated_dwelling
    } else if (p.type === 'water') {
      fontSize = 11; color = '#2171A5';
    } else if (p.type === 'peak') {
      fontSize = 10; color = '#8B4513';
    } else if (p.type === 'road') {
      if (p.class === 'motorway' || p.class === 'trunk' || p.class === 'primary') {
        fontSize = 10; color = '#666666'; bold = true;
      } else if (p.class === 'secondary' || p.class === 'tertiary') {
        fontSize = 9; color = '#777777';
      } else {
        fontSize = 8; color = '#888888';
      }
    } else if (p.type === 'poi') {
      fontSize = 9; color = '#555555';
    }

    const name = p.type === 'peak' && p.ele ? `${p.name} ${p.ele}m` : p.name;

    labels.push({ name, type: p.type, class: p.class, rank: p.rank,
      coordinate: coords, fontSize, color, bold });
  }

  return labels;
}

const allLabels = buildAllLabels();

