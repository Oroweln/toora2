/**
 * RouteMap — MapLibre GL map with offline MBTiles vector tile base layer,
 * route polyline, hotspot checkpoint markers, direction dots,
 * start/end markers, map labels, and live user position.
 *
 * CRITICAL RULES (breaking any of these kills the map silently):
 *  - Base style layers: ONLY fill/line/background. NO symbol layers in base style.
 *  - NO standalone layers without parent ShapeSource.
 *  - Hotspot/start/end markers use MarkerView (native RN views) — works offline.
 *  - Map labels use ShapeSource + SymbolLayer with LOCAL bundled glyph PBFs
 *    (asset://glyphs/{fontstack}/{range}.pbf) — fully offline, GPU-rendered.
 *  - Map geometry overlays use ShapeSource + LineLayer/CircleLayer.
 */

