// Generated by: node scripts/extract-labels.js
// Rendered via SymbolLayer (GPU) with locally bundled glyph PBFs — fully offline
let mapLabelsGeoJSON: GeoJSON.FeatureCollection | null = null;
try {
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  mapLabelsGeoJSON = require('../src/data/map-labels.json');
} catch {
  console.warn('RouteMap: map-labels.json not found — labels will not render');
}

