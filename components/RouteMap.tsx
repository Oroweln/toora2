function StartMarker({ coordinate }: { coordinate: [number, number] }) {
  if (!MapLibreGL) return null;
  return (
    <MapLibreGL.MarkerView coordinate={coordinate} anchor={{ x: 0.5, y: 0.5 }}>
      <View style={markerStyles.startEnd}>
        <View style={[markerStyles.startEndCircle, { backgroundColor: '#27AE60' }]}>
          <Text style={markerStyles.startEndText}>P</Text>
        </View>
        <Text style={markerStyles.startEndLabel}>Partenza</Text>
      </View>
    </MapLibreGL.MarkerView>
  );
}

function EndMarker({ coordinate }: { coordinate: [number, number] }) {
  if (!MapLibreGL) return null;
  return (
    <MapLibreGL.MarkerView coordinate={coordinate} anchor={{ x: 0.5, y: 0.5 }}>
      <View style={markerStyles.startEnd}>
        <View style={[markerStyles.startEndCircle, { backgroundColor: '#E74C3C' }]}>
          <Text style={markerStyles.startEndText}>A</Text>
        </View>
        <Text style={markerStyles.startEndLabel}>Arrivo</Text>
      </View>
    </MapLibreGL.MarkerView>
  );
}

function HotspotMarker({
  hotspot, color, isUnlocked, onPress,
}: {
  hotspot: Hotspot; color: string; isUnlocked: boolean;
  onPress: (hs: Hotspot) => void;
}) {
  if (!MapLibreGL) return null;
  const size = isUnlocked ? 32 : hotspot.isActive ? 26 : 22;
  return (
    <MapLibreGL.MarkerView
      coordinate={[hotspot.longitude, hotspot.latitude]}
      anchor={{ x: 0.5, y: 0.5 }}
    >
      <View style={markerStyles.hotspotContainer} onTouchEnd={() => onPress(hotspot)}>
        <View style={[markerStyles.hotspotCircle, {
          backgroundColor: color,
          borderColor: isUnlocked ? '#FFFFFF' : '#666666',
          width: size, height: size, borderRadius: size / 2,
        }]}>
          <Text style={[markerStyles.hotspotSeq, { fontSize: isUnlocked ? 14 : 11 }]}>
            {hotspot.sequence}
          </Text>
        </View>
        <Text style={markerStyles.hotspotTitle} numberOfLines={2}>
          {hotspot.title}
        </Text>
      </View>
    </MapLibreGL.MarkerView>
  );
}

function MapLabelMarker({ label }: { label: MapLabel }) {
  if (!MapLibreGL) return null;
  return (
    <MapLibreGL.MarkerView
      coordinate={label.coordinate}
      anchor={{ x: 0.5, y: 0.5 }}
      allowOverlap={false}
    >
      <Text style={[
        markerStyles.mapLabel,
        {
          fontSize: label.fontSize,
          color: label.color,
          fontWeight: label.bold ? 'bold' : 'normal',
        },
      ]}>
        {label.name}
      </Text>
    </MapLibreGL.MarkerView>
  );
}

