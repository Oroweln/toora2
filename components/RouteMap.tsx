/**
 * RouteMap — MapLibre GL map with offline MBTiles vector tile base layer,
 * route polyline, hotspot checkpoint markers, direction dots,
 * start/end markers, map labels, and live user position.
 *
 * CRITICAL RULES (breaking any of these kills the map silently):
 *  - Base style layers: ONLY fill/line/background. NO symbol layers.
 *  - NO standalone layers without parent ShapeSource.
 *  - NO SymbolLayer at all — glyphs need internet, app is offline.
 *  - ALL text/markers rendered via MarkerView (native RN views).
 *  - Map geometry overlays use ShapeSource + LineLayer/CircleLayer only.
 */

